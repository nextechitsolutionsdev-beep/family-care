import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';
import {readFileSync} from 'node:fs';
import dotenv from 'dotenv';
import {createClient} from '@supabase/supabase-js';

const env={...process.env,...dotenv.parse(readFileSync('.env'))};
const admin=createClient(env.SUPABASE_URL,env.SUPABASE_SERVER_KEY,{auth:{persistSession:false,autoRefreshToken:false}});
const today=new Intl.DateTimeFormat('en-CA',{timeZone:'Africa/Cairo'}).format(new Date());

test('owner configures a union and reception intake opens one visit on desktop and phone',async({page})=>{
 const suffix=randomUUID().slice(0,8);
 const {data:batch,error:batchError}=await admin.from('demo_batches').insert({name:`Intake E2E ${suffix}`}).select('id').single();
 expect(batchError).toBeNull();
 const {data:dental,error:dentalError}=await admin.from('specialties').select('id').eq('client_prefix','DEN').single();
 expect(dentalError).toBeNull();
 await page.goto('/');
 await page.getByLabel('البريد الإلكتروني').fill(env.OWNER_EMAIL);
 await page.getByLabel('كلمة المرور',{exact:true}).fill(env.OWNER_PASSWORD);
 await page.getByRole('button',{name:'دخول'}).click();
 await expect(page.getByRole('heading',{name:'اليوم'})).toBeVisible();
 await page.goto('/doctors');
 await page.getByRole('button',{name:'طبيب جديد'}).click();
 let form=page.locator('dialog');
 await form.getByLabel('اسم الطبيب').fill(`طبيب تسجيل تجريبي ${suffix}`);
 await form.getByLabel('التخصص').selectOption(dental.id);
 await form.getByLabel('الفئة').selectOption('dentist');
 await form.getByRole('button',{name:'حفظ'}).click();
 await expect(form).toHaveCount(0);
 const {data:doctor,error:doctorError}=await admin.from('doctors').select('id').eq('name',`طبيب تسجيل تجريبي ${suffix}`).single();
 expect(doctorError).toBeNull();
 expect((await admin.from('doctors').update({demo_batch_id:batch.id}).eq('id',doctor.id)).error).toBeNull();
 await page.goto('/insurance');
 await page.getByRole('button',{name:'إضافة نقابة'}).click();
 form=page.locator('dialog');
 await form.getByLabel('اسم النقابة').fill(`نقابة اختبار ${suffix}`);
 await form.getByRole('button',{name:'حفظ'}).click();
 await expect(form).toHaveCount(0);
 const {data:union,error:unionError}=await admin.from('unions').select('id').eq('name',`نقابة اختبار ${suffix}`).single();
 expect(unionError).toBeNull();
 await page.goto('/patients');
 await page.getByRole('button',{name:'تسجيل عميل وخدمة'}).click();
 form=page.locator('dialog');
 await form.getByLabel('اسم العميل').fill(`عميل نقابة تجريبي ${suffix}`);
 await form.getByLabel('رقم الموبايل').fill('+200000000007');
 await form.getByLabel('نوع العميل').selectOption('syndicate_cash');
 await form.getByLabel('النقابة').selectOption(union.id);
 await form.getByLabel('الطبيب والتخصص').selectOption(doctor.id);
 const {data:service,error:serviceError}=await admin.from('services').select('id').eq('seed_code','DEN-001').single();
 expect(serviceError).toBeNull();
 await form.getByLabel('الخدمة').selectOption(service.id);
 await form.getByLabel('نسبة تحمّل العميل من الكارنيه (%)').fill('20');
 await form.getByLabel('المدفوع الآن بالجنيه (اختياري)').fill('60');
 await expect(form.getByText(/العميل عليه 60 جنيه.*على الجهة 240 جنيه.*المدفوع الآن 60 جنيه/)).toBeVisible();
 await form.getByLabel('تاريخ الزيارة').fill(today);
 await form.getByLabel('مجموعة تجريبية (اختياري)').selectOption(batch.id);
 await page.screenshot({path:'docs/review/intake-desktop.jpg',type:'jpeg'});
 await page.setViewportSize({width:390,height:844});
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
 await page.screenshot({path:'docs/review/intake-phone.jpg',type:'jpeg'});
 await form.getByRole('button',{name:'تسجيل العميل والخدمة'}).click();
 await expect(page).toHaveURL(/\/visits\/[0-9a-f-]+$/);
 const visitId=new URL(page.url()).pathname.split('/').at(-1);
 const {data:visit,error:visitError}=await admin.from('visits').select('patient_id,union_id,co_pay_bps,co_pay_minor,covered_minor').eq('id',visitId).single();
 expect(visitError).toBeNull();expect(visit).toMatchObject({union_id:union.id,co_pay_bps:2000,co_pay_minor:6000,covered_minor:24000});
 const {data:payment,error:paymentError}=await admin.from('payments').select('amount_minor').eq('visit_id',visitId).single();
 expect(paymentError).toBeNull();expect(payment.amount_minor).toBe(6000);
 const {data:lines,error:linesError}=await admin.from('visit_lines').select('service_id').eq('visit_id',visitId);
 expect(linesError).toBeNull();expect(lines).toHaveLength(1);expect(lines[0].service_id).toBe(service.id);
 const {data:patient,error:patientError}=await admin.from('patients').select('union_id,demo_batch_id').eq('id',visit.patient_id).single();
 expect(patientError).toBeNull();expect(patient.union_id).toBe(union.id);expect(patient.demo_batch_id).toBe(batch.id);
 await page.goto(`/patients/${visit.patient_id}`);
 await expect(page.getByText(`النقابة: نقابة اختبار ${suffix}`)).toBeVisible();
 await page.getByRole('button',{name:'زيارة جديدة',exact:true}).click();
 form=page.locator('dialog');
 await form.getByLabel('الطبيب').selectOption(doctor.id);
 await form.getByLabel('الخدمة').selectOption(service.id);
 await form.getByLabel('نسبة تحمّل العميل من الكارنيه (%)').fill('20');
 await form.getByRole('button',{name:'إضافة خدمة أخرى'}).click();
 await form.getByLabel('الخدمة الإضافية 1').selectOption(service.id);
 await form.getByLabel('العدد للخدمة 1').fill('2');
 await expect(form.getByText(/العميل عليه 180 جنيه.*على الجهة 720 جنيه/)).toBeVisible();
 await form.getByLabel('الخدمة الإضافية 1').scrollIntoViewIfNeeded();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.screenshot({path:'docs/review/multiple-services-phone.jpg',type:'jpeg'});
 await page.setViewportSize({width:1366,height:768});
 await page.screenshot({path:'docs/review/multiple-services-desktop.jpg',type:'jpeg'});
 await form.getByRole('button',{name:'إلغاء الخدمة 1',exact:true}).click();
 await expect(form.getByText(/العميل عليه 60 جنيه.*على الجهة 240 جنيه/)).toBeVisible();
 await form.getByRole('button',{name:'إضافة خدمة أخرى'}).click();
 await form.getByLabel('الخدمة الإضافية 1').selectOption(service.id);
 await form.getByRole('button',{name:'تسجيل الزيارة والخدمة'}).click();
 await expect(page).toHaveURL(/\/visits\/[0-9a-f-]+$/);
 await expect(page.getByText('الإجمالي').first()).toBeVisible();
 const cancellation=page.locator('tr').filter({has:page.getByRole('button',{name:'إلغاء الخدمة',exact:true})});
 await expect(cancellation).toHaveCount(2);
 page.once('dialog',dialog=>dialog.accept());
 await cancellation.first().getByRole('button',{name:'إلغاء الخدمة',exact:true}).click();
 await expect(cancellation).toHaveCount(1);
 await page.goto('/insurance');
 await page.locator('tr').filter({hasText:`نقابة اختبار ${suffix}`}).getByRole('button',{name:'تعديل'}).click();
 form=page.locator('dialog');
 await form.getByLabel('نشطة ومتاحة للاستقبال').uncheck();
 await form.getByRole('button',{name:'حفظ'}).click();
 await expect(form).toHaveCount(0);
});
