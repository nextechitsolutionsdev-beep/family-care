import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';
import {readFileSync} from 'node:fs';
import dotenv from 'dotenv';
import {createClient} from '@supabase/supabase-js';
import {query} from '../scripts/supabase.mjs';

const env={...process.env,...dotenv.parse(readFileSync('.env'))};
const admin=createClient(env.SUPABASE_URL,env.SUPABASE_SERVER_KEY,{auth:{persistSession:false,autoRefreshToken:false}});
const today=new Intl.DateTimeFormat('en-CA',{timeZone:'Africa/Cairo'}).format(new Date());
const tomorrowDate=new Date(`${today}T12:00:00Z`);tomorrowDate.setUTCDate(tomorrowDate.getUTCDate()+1);
const tomorrow=tomorrowDate.toISOString().slice(0,10);
const dayNames=['الأحد','الإثنين','الثلاثاء','الأربعاء','الخميس','الجمعة','السبت'];

test('doctor share and working day, insurer coverage and Family Care base price',async({page})=>{
 test.setTimeout(240000);
 const suffix=randomUUID().slice(0,8);
 const patientName=`عميل نسبة وتأمين تجريبي ${suffix}`;
 const doctorName=`طبيب نسبة تجريبي ${suffix}`;
 const insurerName=`تأمين نسبة تجريبي ${suffix}`;
 const {data:batch,error:batchError}=await admin.from('demo_batches').insert({name:`Rates E2E ${suffix}`}).select('id').single();
 expect(batchError).toBeNull();
 const {data:dental,error:dentalError}=await admin.from('specialties').select('id').eq('client_prefix','DEN').single();
 expect(dentalError).toBeNull();
 const {data:service,error:serviceError}=await admin.from('services').select('id').eq('seed_code','DEN-001').single();
 expect(serviceError).toBeNull();
 await page.goto('/');
 await page.getByLabel('البريد الإلكتروني').fill(env.OWNER_EMAIL);
 await page.getByLabel('كلمة المرور',{exact:true}).fill(env.OWNER_PASSWORD);
 await page.getByRole('button',{name:'دخول'}).click();
 await expect(page.getByRole('heading',{name:'اليوم'})).toBeVisible();

 await page.goto('/doctors');
 await page.getByRole('button',{name:'طبيب جديد'}).click();
 let form=page.locator('dialog');
 await form.getByLabel('اسم الطبيب').fill(doctorName);
 await form.getByLabel('التخصص').selectOption(dental.id);
 await form.getByLabel('الفئة').selectOption('percentage');
 await form.getByLabel('النسبة من التحصيل (%)').fill('33.33');
 await form.getByRole('checkbox',{name:dayNames[tomorrowDate.getUTCDay()]}).check();
 await form.getByRole('button',{name:'حفظ'}).click();
 await expect(form).toHaveCount(0);
 const {data:doctor,error:doctorError}=await admin.from('doctors').select('id,schedule,default_share_bps').eq('name',doctorName).single();
 expect(doctorError).toBeNull();expect(doctor.default_share_bps).toBe(3333);
 expect(doctor.schedule).toEqual([tomorrowDate.getUTCDay()]);
 expect((await admin.from('doctors').update({demo_batch_id:batch.id}).eq('id',doctor.id)).error).toBeNull();

 await page.goto('/insurance');
 await page.getByRole('button',{name:'إضافة شركة تأمين'}).click();
 form=page.locator('dialog');
 await form.getByLabel('اسم الشركة').fill(insurerName);
 await form.getByLabel('بيانات التواصل').fill('رقم اختبار داخلي');
 await form.getByRole('button',{name:'حفظ'}).click();
 await expect(form).toHaveCount(0);
 const {data:insurer,error:insurerError}=await admin.from('insurance_companies').select('id,contact').eq('name',insurerName).single();
 expect(insurerError).toBeNull();expect(insurer.contact).toBe('رقم اختبار داخلي');
 expect((await admin.from('insurance_companies').update({demo_batch_id:batch.id}).eq('id',insurer.id)).error).toBeNull();
 const companyRow=page.locator('tr').filter({hasText:insurerName});
 await expect(companyRow).toContainText('رقم اختبار داخلي');

 await page.goto('/patients');
 await page.getByRole('button',{name:'تسجيل عميل وخدمة'}).click();
 form=page.locator('dialog');
 await form.getByLabel('اسم العميل').fill(patientName);
 await form.getByLabel('رقم الموبايل').fill('+200000000008');
 await form.getByLabel('نوع العميل').selectOption('insurance_credit');
 await form.getByLabel('شركة التأمين').selectOption(insurer.id);
 await form.getByLabel('نسبة تحمّل العميل من الكارنيه (%)').fill('20');
 await form.getByLabel('الطبيب والتخصص').selectOption(doctor.id);
 await form.getByLabel('الخدمة').selectOption(service.id);
 await expect(form.getByText(/العميل عليه 60 جنيه.*على الجهة 240 جنيه/)).toBeVisible();
 await form.getByLabel('مجموعة تجريبية (اختياري)').selectOption(batch.id);
 await form.getByLabel('تاريخ الزيارة').fill(today);
 await form.getByRole('button',{name:'تسجيل العميل والخدمة'}).click();
 await expect(form.getByRole('alert')).toContainText('الطبيب غير متاح');
 const {count:rolledBack}=await admin.from('patients').select('id',{count:'exact',head:true}).eq('name',patientName);
 expect(rolledBack).toBe(0);
 await form.getByLabel('تاريخ الزيارة').fill(tomorrow);
 await form.getByRole('button',{name:'تسجيل العميل والخدمة'}).click();
 await expect(page).toHaveURL(/\/visits\/[0-9a-f-]+$/);
 const visitId=new URL(page.url()).pathname.split('/').at(-1);
 await expect(page.getByText(/العميل يتحمل 20% · الجهة تغطي 80%/)).toBeVisible();

 const charged=query(`select l.unit_price_minor,l.doctor_share_bps,pl.client_type_code from public.visit_lines l join public.price_list_versions pv on pv.id=l.list_version_id join public.price_lists pl on pl.id=pv.list_id where l.visit_id='${visitId}' and l.service_id='${service.id}';`)[0];
 expect(charged.client_type_code).toBe('family_care_cash');
 expect(charged.unit_price_minor).toBe(30000);expect(charged.doctor_share_bps).toBe(3333);
 const {data:split,error:splitError}=await admin.from('visits').select('total_minor,co_pay_minor,covered_minor,co_pay_bps').eq('id',visitId).single();
 expect(splitError).toBeNull();expect(split).toMatchObject({total_minor:30000,co_pay_minor:6000,covered_minor:24000,co_pay_bps:2000});

 await page.goto('/doctors');
 await page.locator('tr').filter({hasText:doctorName}).getByRole('button',{name:'تعديل'}).click();
 form=page.locator('dialog');
 await form.getByLabel('النسبة من التحصيل (%)').fill('50');
 await form.getByRole('button',{name:'حفظ'}).click();
 await expect(form).toHaveCount(0);
 await page.goto(`/visits/${visitId}`);
 await page.getByRole('button',{name:'تسجيل تحصيل'}).click();
 form=page.locator('dialog');
 await form.getByLabel('المبلغ بالجنيه').fill('60');
 await form.getByRole('button',{name:'تسجيل وطباعة الإيصال'}).click();
 await expect(page.getByRole('heading',{name:'إيصال التحصيل'})).toBeVisible();
 await page.locator('dialog').getByRole('button',{name:'إغلاق'}).click();
 await page.getByRole('button',{name:'الكشف وإنهاء الزيارة'}).click();
 form=page.locator('dialog');
 await form.getByLabel('التشخيص / ملاحظات الكشف').fill('فحص تجريبي للنسب');
 await form.getByRole('button',{name:'حفظ وإنهاء الزيارة'}).click();
 await expect(form).toHaveCount(0);
 await page.goto('/insurance');
 await page.locator('tr').filter({hasText:insurerName}).getByRole('button',{name:'تسوية'}).click();
 form=page.locator('dialog');
 await form.getByLabel('المبلغ بالجنيه').fill('240');
 await form.getByRole('button',{name:'تسجيل التسوية'}).click();
 await expect(form).toHaveCount(0);
 const shares=query(`select (select coalesce(sum(a.doctor_share_minor),0) from public.payment_allocations a join public.payments p on p.id=a.payment_id where p.visit_id='${visitId}' and p.kind<>'refund') patient_share,(select coalesce(sum(a.doctor_share_minor),0) from public.settlement_allocations a join public.insurance_invoices i on i.id=a.invoice_id join public.insurance_settlements s on s.id=a.settlement_id where i.visit_id='${visitId}' and s.reverses_settlement_id is null) insurer_share;`)[0];
 expect(BigInt(shares.patient_share)).toBe(2000n);
 expect(BigInt(shares.insurer_share)).toBe(7999n);
 await page.goto('/doctors');
 await expect(page.getByRole('heading',{name:'الأطباء وحساباتهم'})).toBeVisible();
 await page.locator('.filters select').first().selectOption(doctor.id);
 await page.getByRole('button',{name:'عرض الحساب'}).click();
 await expect(page.getByText('99.99 جنيه').first()).toBeVisible();
});
